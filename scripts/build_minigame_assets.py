#!/usr/bin/env python3
"""Generate lightweight optimized assets and vector emblems for the WeChat Mini Game bundle."""

import json
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image

UNIT_EMBLEMS = [
    'flame',
    'meteor',
    'horn',
    'cake',
    'hummingbird',
    'microphone',
    'bat',
    'snow',
    'scythe',
    'cartridge',
    'flower',
    'branch',
    'giant',
    'cloak',
    'portal',
    'quill',
    'sunflower',
    'phoenixleaf',
    'bloodmoon',
    'star',
]

EMBLEMS_TS_TEMPLATE = r"""/* Auto-generated by scripts/build_minigame_assets.py from frontend/public/icons/*.svg */

export const EMBLEM_PATHS: Record<string, string[]> = __EMBLEMS_JSON__;

const TOKEN_RE = /[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?/g;

function drawEllipticalArc(
  ctx: WxCanvasRenderingContext2D,
  x0: number,
  y0: number,
  rxIn: number,
  ryIn: number,
  phiDeg: number,
  largeArc: number,
  sweep: number,
  x: number,
  y: number,
): void {
  if (x0 === x && y0 === y) return;
  let rx = Math.abs(rxIn);
  let ry = Math.abs(ryIn);
  if (rx === 0 || ry === 0) {
    ctx.lineTo(x, y);
    return;
  }

  const phi = (phiDeg * Math.PI) / 180;
  const cosPhi = Math.cos(phi);
  const sinPhi = Math.sin(phi);
  const dx2 = (x0 - x) / 2;
  const dy2 = (y0 - y) / 2;
  const x1p = cosPhi * dx2 + sinPhi * dy2;
  const y1p = -sinPhi * dx2 + cosPhi * dy2;

  const rxSq = rx * rx;
  const rySq = ry * ry;
  const x1pSq = x1p * x1p;
  const y1pSq = y1p * y1p;
  const lambda = x1pSq / rxSq + y1pSq / rySq;
  if (lambda > 1) {
    const s = Math.sqrt(lambda);
    rx *= s;
    ry *= s;
  }

  const rxs = rx * rx;
  const rys = ry * ry;
  const num = Math.max(0, rxs * rys - rxs * y1pSq - rys * x1pSq);
  const den = rxs * y1pSq + rys * x1pSq;
  const factor = den === 0 ? 0 : Math.sqrt(num / den) * (largeArc === sweep ? -1 : 1);
  const cxp = factor * ((rx * y1p) / ry);
  const cyp = factor * (-(ry * x1p) / rx);

  const cx = cosPhi * cxp - sinPhi * cyp + (x0 + x) / 2;
  const cy = sinPhi * cxp + cosPhi * cyp + (y0 + y) / 2;

  const vecAngle = (ux: number, uy: number, vx: number, vy: number): number => {
    const dot = ux * vx + uy * vy;
    const len = Math.hypot(ux, uy) * Math.hypot(vx, vy);
    const cos = Math.max(-1, Math.min(1, len === 0 ? 1 : dot / len));
    let ang = Math.acos(cos);
    if (ux * vy - uy * vx < 0) ang = -ang;
    return ang;
  };

  const ux = (x1p - cxp) / rx;
  const uy = (y1p - cyp) / ry;
  const vx = (-x1p - cxp) / rx;
  const vy = (-y1p - cyp) / ry;
  const theta1 = vecAngle(1, 0, ux, uy);
  let dTheta = vecAngle(ux, uy, vx, vy);
  if (!sweep && dTheta > 0) dTheta -= Math.PI * 2;
  if (sweep && dTheta < 0) dTheta += Math.PI * 2;

  const steps = Math.max(8, Math.ceil((Math.abs(dTheta) / (Math.PI * 2)) * 28));
  for (let i = 1; i <= steps; i += 1) {
    const th = theta1 + (dTheta * i) / steps;
    const px = cx + cosPhi * rx * Math.cos(th) - sinPhi * ry * Math.sin(th);
    const py = cy + sinPhi * rx * Math.cos(th) + cosPhi * ry * Math.sin(th);
    ctx.lineTo(px, py);
  }
}

function strokeSvgPath(ctx: WxCanvasRenderingContext2D, d: string): void {
  const tokens = d.match(TOKEN_RE);
  if (!tokens) return;

  let i = 0;
  let cmd = '';
  let cx = 0;
  let cy = 0;
  let sx = 0;
  let sy = 0;
  let prevQx = 0;
  let prevQy = 0;
  let prevCmd = '';

  const num = () => Number(tokens[i++]);
  const isNum = () => i < tokens.length && !/^[A-Za-z]$/.test(tokens[i]);

  ctx.beginPath();
  while (i < tokens.length) {
    if (/^[A-Za-z]$/.test(tokens[i])) {
      cmd = tokens[i++];
    }
    switch (cmd) {
      case 'M': {
        cx = num();
        cy = num();
        sx = cx;
        sy = cy;
        ctx.moveTo(cx, cy);
        prevCmd = 'M';
        while (isNum()) {
          cx = num();
          cy = num();
          ctx.lineTo(cx, cy);
          prevCmd = 'L';
        }
        break;
      }
      case 'L':
        while (isNum()) {
          cx = num();
          cy = num();
          ctx.lineTo(cx, cy);
        }
        prevCmd = 'L';
        break;
      case 'H':
        while (isNum()) {
          cx = num();
          ctx.lineTo(cx, cy);
        }
        prevCmd = 'H';
        break;
      case 'V':
        while (isNum()) {
          cy = num();
          ctx.lineTo(cx, cy);
        }
        prevCmd = 'V';
        break;
      case 'C':
        while (isNum()) {
          const x1 = num();
          const y1 = num();
          const x2 = num();
          const y2 = num();
          cx = num();
          cy = num();
          ctx.bezierCurveTo(x1, y1, x2, y2, cx, cy);
        }
        prevCmd = 'C';
        break;
      case 'Q':
        while (isNum()) {
          prevQx = num();
          prevQy = num();
          cx = num();
          cy = num();
          ctx.quadraticCurveTo(prevQx, prevQy, cx, cy);
          prevCmd = 'Q';
        }
        break;
      case 'T':
        while (isNum()) {
          const qx = prevCmd === 'Q' || prevCmd === 'T' ? 2 * cx - prevQx : cx;
          const qy = prevCmd === 'Q' || prevCmd === 'T' ? 2 * cy - prevQy : cy;
          prevQx = qx;
          prevQy = qy;
          cx = num();
          cy = num();
          ctx.quadraticCurveTo(qx, qy, cx, cy);
          prevCmd = 'T';
        }
        break;
      case 'A':
        while (isNum()) {
          const rx = num();
          const ry = num();
          const rot = num();
          const largeArc = num();
          const sweep = num();
          const nx = num();
          const ny = num();
          drawEllipticalArc(ctx, cx, cy, rx, ry, rot, largeArc, sweep, nx, ny);
          cx = nx;
          cy = ny;
        }
        prevCmd = 'A';
        break;
      case 'Z':
      case 'z':
        ctx.closePath();
        cx = sx;
        cy = sy;
        prevCmd = 'Z';
        break;
      default:
        i += 1;
        break;
    }
  }
  ctx.stroke();
}

export function drawEmblemIcon(
  ctx: WxCanvasRenderingContext2D,
  emblemName: string,
  cx: number,
  cy: number,
  size: number,
  strokeColor: string,
  lineWidth = 2.4,
): void {
  const paths = EMBLEM_PATHS[emblemName] || EMBLEM_PATHS.star;
  if (!paths || paths.length === 0) return;

  const scale = size / 64;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(scale, scale);
  ctx.strokeStyle = strokeColor;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.lineWidth = Math.max(2.5, lineWidth / scale);
  for (const d of paths) {
    strokeSvgPath(ctx, d);
  }
  ctx.restore();
}
"""


def _extract_emblems(project_root: Path) -> dict[str, list[str]]:
    icons_dir = project_root / 'frontend' / 'public' / 'icons'
    result: dict[str, list[str]] = {}
    for name in UNIT_EMBLEMS:
        svg_path = icons_dir / f'{name}.svg'
        if not svg_path.is_file():
            raise FileNotFoundError(f'Missing emblem SVG: {svg_path}')
        root = ET.parse(svg_path).getroot()
        paths = [
            el.attrib['d'].strip()
            for el in root.iter()
            if el.tag.split('}')[-1] == 'path' and el.attrib.get('d')
        ]
        result[name] = paths
    return result


def build_emblems_ts(project_root: Path) -> Path:
    emblems = _extract_emblems(project_root)
    out_file = project_root / 'minigame' / 'src' / 'engine' / 'emblems.ts'
    out_file.parent.mkdir(parents=True, exist_ok=True)
    emblems_json = json.dumps(emblems, ensure_ascii=False, indent=2)
    content = EMBLEMS_TS_TEMPLATE.replace('__EMBLEMS_JSON__', emblems_json)
    out_file.write_text(content, encoding='utf-8')
    print(f'Generated {out_file} ({len(emblems)} emblems)')
    return out_file


def build_assets(root: Path | None = None) -> list[Path]:
    project_root = root or Path(__file__).resolve().parent.parent
    src_logo = project_root / 'frontend' / 'public' / 'logo.png'
    out_dir = project_root / 'minigame' / 'static' / 'assets'
    out_dir.mkdir(parents=True, exist_ok=True)
    outputs: list[Path] = []

    if src_logo.is_file():
        dst_logo = out_dir / 'logo.png'
        with Image.open(src_logo) as img:
            converted = img.convert('RGBA')
            resized = converted.resize((192, 192), Image.Resampling.LANCZOS)
            resized.save(dst_logo, format='PNG', optimize=True)
        outputs.append(dst_logo)
        print(f'Generated {dst_logo} ({dst_logo.stat().st_size} bytes)')
    else:
        raise FileNotFoundError(f'Source logo not found: {src_logo}')

    outputs.append(build_emblems_ts(project_root))
    return outputs


if __name__ == '__main__':
    build_assets()
